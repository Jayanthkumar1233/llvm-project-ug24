#ifndef LLVM_LIB_TARGET_UG24_MCTARGETDESC_UG24INSTPRINTER_H
#define LLVM_LIB_TARGET_UG24_MCTARGETDESC_UG24INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class UG24InstPrinter : public MCInstPrinter {
public:
  UG24InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &OS, MCRegister Reg) const override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &OS) override;

  // Generated by TableGen
  std::pair<const char *, uint64_t> getMnemonic(const MCInst *MI) override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &OS);
  static const char *getRegisterName(MCRegister Reg);

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImmOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm8(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemDisp(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printFrameSlot(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemRI(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBranchTarget(const MCInst *MI, uint64_t Address, unsigned OpNo,
                         raw_ostream &O);
  void printCallTarget(const MCInst *MI, unsigned OpNo, raw_ostream &O);
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_UG24_MCTARGETDESC_UG24INSTPRINTER_H
