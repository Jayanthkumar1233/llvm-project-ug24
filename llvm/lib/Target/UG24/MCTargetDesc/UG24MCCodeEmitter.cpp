#include "llvm/MC/MCCodeEmitter.h"
#include "llvm/MC/MCContext.h"
#include "llvm/MC/MCExpr.h"
#include "llvm/MC/MCInst.h"
#include "llvm/MC/MCInstrInfo.h"
#include "llvm/MC/MCRegisterInfo.h"
#include "llvm/MC/MCSubtargetInfo.h"
#include "llvm/Support/EndianStream.h"
#include "llvm/Support/raw_ostream.h"

using namespace llvm;

#define DEBUG_TYPE "mccodeemitter"

namespace {
class UG24MCCodeEmitter : public MCCodeEmitter {
  const MCInstrInfo &MCII;
  MCContext &Ctx;

public:
  UG24MCCodeEmitter(const MCInstrInfo &MCII, MCContext &Ctx)
      : MCII(MCII), Ctx(Ctx) {}

  void encodeInstruction(const MCInst &MI, raw_ostream &OS,
                         SmallVectorImpl<MCFixup> &Fixups,
                         const MCSubtargetInfo &STI) const override;

  // Generated by TableGen.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;

  unsigned getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &Fixups,
                             const MCSubtargetInfo &STI) const;

  // INC/DEC and the shifts encode "amount - 1".
  unsigned getImmMinus1OpValue(const MCInst &MI, unsigned OpNo,
                               SmallVectorImpl<MCFixup> &Fixups,
                               const MCSubtargetInfo &STI) const;

  unsigned getBranchTargetOpValue(const MCInst &MI, unsigned OpNo,
                                  SmallVectorImpl<MCFixup> &Fixups,
                                  const MCSubtargetInfo &STI) const;

  unsigned getCallTargetOpValue(const MCInst &MI, unsigned OpNo,
                                SmallVectorImpl<MCFixup> &Fixups,
                                const MCSubtargetInfo &STI) const;
};
} // namespace

void UG24MCCodeEmitter::encodeInstruction(const MCInst &MI, raw_ostream &OS,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  uint64_t Binary = getBinaryCodeForInstr(MI, Fixups, STI);
  unsigned Size = MCII.get(MI.getOpcode()).getSize();

  switch (Size) {
  case 2:
    support::endian::write<uint16_t>(OS, static_cast<uint16_t>(Binary),
                                     llvm::support::endianness::little);
    break;
  case 4:
    // The opcode halfword is fetched first, so it occupies the low 16 bits of
    // the little-endian word.
    support::endian::write<uint32_t>(OS, static_cast<uint32_t>(Binary),
                                     llvm::support::endianness::little);
    break;
  default:
    llvm_unreachable("unsupported uG24 instruction size");
  }
}

unsigned
UG24MCCodeEmitter::getMachineOpValue(const MCInst &MI, const MCOperand &MO,
                                     SmallVectorImpl<MCFixup> &Fixups,
                                     const MCSubtargetInfo &STI) const {
  if (MO.isReg())
    return Ctx.getRegisterInfo()->getEncodingValue(MO.getReg());
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());

  assert(MO.isExpr() && "unexpected operand kind");
  const MCExpr *Expr = MO.getExpr();

  // An 8-bit immediate field can only hold one byte of a 16-bit address, so
  // the expression says which byte it wants.  A bare symbol defaults to the
  // low byte.
  auto Kind = UG24::fixup_ug24_lo8;
  if (const auto *UE = dyn_cast<UG24MCExpr>(Expr))
    if (UE->getKind() == UG24MCExpr::VK_UG24_HI8)
      Kind = UG24::fixup_ug24_hi8;

  Fixups.push_back(
      MCFixup::create(0, Expr, MCFixupKind(Kind), MI.getLoc()));
  return 0;
}

unsigned
UG24MCCodeEmitter::getImmMinus1OpValue(const MCInst &MI, unsigned OpNo,
                                       SmallVectorImpl<MCFixup> &Fixups,
                                       const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  assert(MO.isImm() && "expected an immediate shift/step amount");
  int64_t Value = MO.getImm();
  assert(Value >= 1 && "shift/step amount must be at least 1");
  return static_cast<unsigned>(Value - 1);
}

unsigned
UG24MCCodeEmitter::getBranchTargetOpValue(const MCInst &MI, unsigned OpNo,
                                          SmallVectorImpl<MCFixup> &Fixups,
                                          const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);

  // An already-resolved offset is given in bytes and must be scaled to
  // instruction words.
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm()) >> 1;

  assert(MO.isExpr() && "expected a branch target expression");
  Fixups.push_back(MCFixup::create(0, MO.getExpr(),
                                   MCFixupKind(UG24::fixup_ug24_pcrel_10),
                                   MI.getLoc()));
  return 0;
}

unsigned
UG24MCCodeEmitter::getCallTargetOpValue(const MCInst &MI, unsigned OpNo,
                                        SmallVectorImpl<MCFixup> &Fixups,
                                        const MCSubtargetInfo &STI) const {
  const MCOperand &MO = MI.getOperand(OpNo);
  if (MO.isImm())
    return static_cast<unsigned>(MO.getImm());

  assert(MO.isExpr() && "expected a call target expression");
  // The address occupies the second halfword, i.e. byte offset 2.
  Fixups.push_back(MCFixup::create(2, MO.getExpr(),
                                   MCFixupKind(UG24::fixup_ug24_abs_16),
                                   MI.getLoc()));
  return 0;
}

#include "UG24GenMCCodeEmitter.inc"

MCCodeEmitter *llvm::createUG24MCCodeEmitter(const MCInstrInfo &MCII,
                                             MCContext &Ctx) {
  return new UG24MCCodeEmitter(MCII, Ctx);
}
